"""
Unit Tests for Sanitized CAPE Sandbox v2 Schema Export Ingestion & Provenance (Milestone 5).
Verifies:
1. Accurate ingestion of sanitized CAPE v2.2 schema export structure.
2. Correct normalization of processes, dropped files, and network events.
3. 100% bidirectional resolution of RFC 6901 JSON Pointers against the schema export fixture.
4. Clean surfacing of unmapped/unsupported vendor sections without silent omission.
"""

import json
from pathlib import Path
import unittest

from engine.parsers.cape_parser import parse_cape_report
from engine.provenance import resolve_json_pointer


class TestRealCapeIngestion(unittest.TestCase):
    def setUp(self):
        parent_dir = Path(__file__).resolve().parent
        base_dir = parent_dir.parent if (parent_dir.parent / "data").exists() else parent_dir
        fixture_path = base_dir / "data/real_sanitized_cape_v2_export.json"
        with open(fixture_path, "r") as f:
            self.raw_cape = json.load(f)

    def test_sanitized_cape_schema_version_and_target(self):
        """
        Verify that the parser correctly extracts CAPE version and primary sample SHA-256.
        """
        report = parse_cape_report(self.raw_cape, report_id="real_cape_v2")
        self.assertEqual(report.sandbox_name, "CAPE Sandbox 2.2-CAPE")
        self.assertEqual(report.schema_format, "cape_v2_native_2.2-CAPE")
        self.assertEqual(report.schema_provenance_type, "DOCUMENTED_VENDOR_FORMAT")
        self.assertEqual(
            report.sample_sha256,
            "7f83b1657ff1fc53b92dc18148a1d65dfc2d4b1fa3d677284addd200126d9069"
        )
        self.assertEqual(report.duration_seconds, 123)

    def test_parsed_fields_and_entities(self):
        """
        Verify that processes, dropped files, and network events are extracted accurately.
        """
        report = parse_cape_report(self.raw_cape, report_id="real_cape_v2")

        # 4 processes
        self.assertEqual(len(report.processes), 4)
        proc_names = [p.image_name for p in report.processes]
        self.assertIn("invoice_doc_sanitized.exe", proc_names)
        self.assertIn("cmd.exe", proc_names)
        self.assertIn("powershell.exe", proc_names)
        self.assertIn("update_payload.exe", proc_names)

        # 2 dropped files
        self.assertEqual(len(report.dropped_files), 2)
        dropped_hashes = [d.sha256 for d in report.dropped_files]
        self.assertIn("a1b2c3d4e5f67890123456789abcdef0123456789abcdef0123456789abcdef0", dropped_hashes)
        self.assertIn("c5e8f1b2d49a37210e4fbc8712a0956487e41203876541290384756102938475", dropped_hashes)

        # Network events: 1 DNS, 1 HTTP, 2 TCP
        self.assertEqual(len(report.network_events), 4)

    def test_rfc6901_pointers_resolve_against_schema_fixture(self):
        """
        Verify that EVERY pointer generated by the parser resolves to a valid node in the fixture raw JSON.
        """
        report = parse_cape_report(self.raw_cape, report_id="real_cape_v2")

        # Check process pointers
        for proc in report.processes:
            ptr = proc.evidence.json_pointer
            self.assertTrue(ptr.startswith("/behavior/processes/"))
            node = resolve_json_pointer(self.raw_cape, ptr)
            self.assertIsNotNone(node)
            self.assertEqual(node["process_name"], proc.image_name)

        # Check dropped file pointers
        for df in report.dropped_files:
            ptr = df.evidence.json_pointer
            self.assertTrue(ptr.startswith("/dropped/"))
            node = resolve_json_pointer(self.raw_cape, ptr)
            self.assertIsNotNone(node)
            self.assertEqual(node["sha256"], df.sha256)

        # Check network pointers
        for net in report.network_events:
            ptr = net.evidence.json_pointer
            self.assertTrue(ptr.startswith("/network/"))
            node = resolve_json_pointer(self.raw_cape, ptr)
            self.assertIsNotNone(node)

    def test_unsupported_fields_cleanly_surfaced(self):
        """
        Verify that unsupported sections (signatures, memory, apistats, debug)
        are explicitly captured in unsupported_fields and not silently swallowed.
        """
        report = parse_cape_report(self.raw_cape, report_id="real_cape_v2")
        unsupported_str = " ".join(report.unsupported_fields)

        self.assertIn("signatures", unsupported_str)
        self.assertIn("memory", unsupported_str)
        self.assertIn("apistats", unsupported_str)
        self.assertIn("debug", unsupported_str)
        self.assertIn("behavior.summary.keys", unsupported_str)
        self.assertIn("behavior.summary.mutexes", unsupported_str)


if __name__ == "__main__":
    unittest.main()
